#####
##### Transitions: (state, action) -> (next state, reward)
#####

"""
    DynamicsTransition

One ground-truth transition of the planning domain, generated by
playing an available action from a reachable partial plan:
`state` is the partial plan before the action, `action` is the
allocation (crop, ha), `next_state` is the partial plan after it,
and `reward` is the plan-quality reward of that step (0 for an
intermediate step, delivered / total demand at the terminal step).
`spec` is the (synthetic, varied) spec the transition was
generated under. Transitions are domain ground truth, not
verified samples: they describe how the domain behaves, and
they never carry a verified flag.
"""
struct DynamicsTransition
    spec::FoodPlanSpec
    state::PlanState
    action::Tuple{Int, Float64}
    next_state::PlanState
    reward::Float64
end

"""
    generate_transitions(base_spec, seeds) -> Vector{DynamicsTransition}

Generate every reachable transition of the planning domain under
each varied spec named by `seeds` (see vary_spec in
training_loop.jl): from the empty plan, every available wheat
action; from each resulting one-crop plan, every available
potato action. Terminal states are not expanded. Deterministic:
same seeds -> same transitions. Synthetic specs only, never a
real region.
"""
function generate_transitions(base_spec::FoodPlanSpec,
                              seeds::AbstractVector{Int})
    transitions = DynamicsTransition[]
    for s in seeds
        spec = vary_spec(base_spec, s)
        # Reachable states: the empty plan, then every plan
        # reached by one available wheat action.
        states = PlanState[(0.0, 0.0, 0)]
        game0 = GI.init(spec)
        for a in GI.available_actions(game0)
            g = GI.clone(game0)
            GI.play!(g, a)
            push!(states, GI.current_state(g))
        end
        for state in states
            game = GI.init(spec, state)
            for a in GI.available_actions(game)
                g = GI.clone(game)
                GI.play!(g, a)
                next_state = GI.current_state(g)
                push!(transitions, DynamicsTransition(
                    spec, state, a, next_state,
                    GI.white_reward(g)))
            end
        end
    end
    return transitions
end

#####
##### State-action features
#####

const N_DYNAMICS_FEATURES = 11  # 8 plan features + crop one-hot (2) + ha share
const N_DYNAMICS_OUTPUTS = 9    # 8 next-state features + reward

"""
    dynamics_features(spec, state, action) -> Vector{Float64}

Eleven features of a (state, action) pair: the eight
spec-normalised plan features of the state (see plan_features),
a one-hot crop indicator (wheat [1, 0], potato [0, 1]), and the
allocated area as a share of the land budget. Every feature is
in [0, 1] for a feasible state and an available action.
"""
function dynamics_features(spec::FoodPlanSpec, state::PlanState,
                           action::Tuple{Int, Float64})
    feats = plan_features(spec, state)
    crop, ha = action
    return Float64[
        feats...,
        crop == 1 ? 1.0 : 0.0,
        crop == 2 ? 1.0 : 0.0,
        ha / spec.land_max,
    ]
end

#####
##### The dynamics model: ridge regression, stdlib only
#####

"""
    DynamicsModel

A learned dynamics model: a ridge-regression weight matrix
mapping state-action features (plus a bias term) to
next-state features plus reward. `weights` is
(N_DYNAMICS_FEATURES + 1) x N_DYNAMICS_OUTPUTS; `fitted` is
false for the neutral model built from no transitions, which
predicts the current state's features and zero reward instead
of pretending to know the dynamics. No hidden layers, no
network library: the weights are plain numbers a human can
read, and the model is small enough to fit in one matrix.

Known limitation (by design): the model is linear in the
features, so — like the linear value model — it cannot express
interactions the features do not carry (e.g. water committed
to wheat while potato still needs water). Whether the learned
search actually helps is therefore judged by the held-out
comparison, exactly as for the linear oracle, and a worse
oracle is never adopted.
"""
struct DynamicsModel
    weights::Matrix{Float64}
    fitted::Bool
end

"""
    fit_dynamics_model(transitions; ridge=1.0) -> DynamicsModel

Fit the dynamics model by multi-output ridge least squares on
the given transitions: state-action features (plus bias)
against next-state features plus reward. Transitions with
non-finite features, targets, or rewards are skipped, never
trained on. With no usable transitions, return the neutral
(unfitted) model.
"""
function fit_dynamics_model(
        transitions::AbstractVector{DynamicsTransition};
        ridge::Float64=1.0)
    usable = DynamicsTransition[]
    for t in transitions
        feats = dynamics_features(t.spec, t.state, t.action)
        targets = vcat(plan_features(t.spec, t.next_state),
                       [t.reward])
        if all(isfinite.(feats)) && all(isfinite.(targets))
            push!(usable, t)
        end
    end
    if isempty(usable)
        return DynamicsModel(
            zeros(Float64, N_DYNAMICS_FEATURES + 1,
                  N_DYNAMICS_OUTPUTS), false)
    end
    n = length(usable)
    X = Matrix{Float64}(undef, n, N_DYNAMICS_FEATURES + 1)
    Y = Matrix{Float64}(undef, n, N_DYNAMICS_OUTPUTS)
    for i in 1:n
        t = usable[i]
        X[i, 1:N_DYNAMICS_FEATURES] .=
            dynamics_features(t.spec, t.state, t.action)
        X[i, N_DYNAMICS_FEATURES + 1] = 1.0
        Y[i, 1:(N_DYNAMICS_OUTPUTS - 1)] .=
            plan_features(t.spec, t.next_state)
        Y[i, N_DYNAMICS_OUTPUTS] = t.reward
    end
    W = (X' * X + ridge * I) \ (X' * Y)
    return DynamicsModel(Matrix{Float64}(W), true)
end

"""
    predict_transition(model, spec, state, action)
        -> (next_features, reward)

Predict the next-state features and the step reward for taking
`action` from `state` under `spec`. Next-state features are
clamped to [0, 1] and the reward to [0, 1]. An unfitted model
predicts the current state's features and zero reward — it
does not invent dynamics it has not been trained on. A
non-finite input returns the same neutral prediction.
"""
function predict_transition(model::DynamicsModel,
                            spec::FoodPlanSpec, state::PlanState,
                            action::Tuple{Int, Float64})
    feats = dynamics_features(spec, state, action)
    if !model.fitted || !all(isfinite.(feats))
        return (plan_features(spec, state), 0.0)
    end
    y = vec(model.weights' *
            vcat(feats, 1.0))
    next_feats = clamp.(y[1:(N_DYNAMICS_OUTPUTS - 1)], 0.0, 1.0)
    reward = clamp(y[N_DYNAMICS_OUTPUTS], 0.0, 1.0)
    return (next_feats, reward)
end

"""
    dynamics_prediction_error(model, transitions)
        -> (mean_abs_error, max_abs_error)

Mean and maximum absolute prediction error of `model` over
`transitions`, pooling all nine outputs (eight next-state
features and the reward). Returns (NaN, NaN) for an empty
transition list. Use this to MEASURE the error first, then set
any test threshold from what the model actually achieves —
never assert an unmeasured number.
"""
function dynamics_prediction_error(
        model::DynamicsModel,
        transitions::AbstractVector{DynamicsTransition})
    isempty(transitions) && return (NaN, NaN)
    total = 0.0
    max_err = 0.0
    count = 0
    for t in transitions
        next_feats, reward =
            predict_transition(model, t.spec, t.state, t.action)
        truth = vcat(plan_features(t.spec, t.next_state),
                     [t.reward])
        pred = vcat(next_feats, [reward])
        for k in 1:N_DYNAMICS_OUTPUTS
            err = abs(pred[k] - truth[k])
            total += err
            max_err = max(max_err, err)
            count += 1
        end
    end
    return (total / count, max_err)
end

#####
##### Reconstructing a plan state from predicted features
#####

"""
    state_from_features(spec, features) -> PlanState

Reconstruct the (unique) plan state on the action grid whose
features are closest to `features`: areas are snapped to the
nearest available wheat / potato option, the step is the
rounded feature value clamped to 0..2. The plan features are
invertible for areas and step on this domain (features 1, 2
and 3 are area / land budget and step / 2), so the snapping
only corrects small prediction error — it never invents a
state off the grid.
"""
function state_from_features(spec::FoodPlanSpec,
                             features::AbstractVector{Float64})
    wheat_ha = clamp(features[1] * spec.land_max, 0.0, spec.land_max)
    potato_ha = clamp(features[2] * spec.land_max, 0.0, spec.land_max)
    step = clamp(round(Int, features[3] * 2.0), 0, 2)
    snap(x, options) = options[argmin(abs.(options .- x))]
    return (snap(wheat_ha, spec.wheat_options),
            snap(potato_ha, spec.potato_options), step)
end

"""
    predict_dynamics_value(model, spec, state) -> Float64

Estimated plan quality reachable from `state`, computed by
lookahead through the learned dynamics model only: the maximum
predicted final delivered share over the available actions,
where each step's successor state comes from predict_transition
(the successor is reconstructed with state_from_features and
the lookahead recurses; the domain is two decisions deep, so
the recursion terminates at the terminal step, whose value is
its delivered share — the transition reward into a terminal
state already IS that delivered share, so it is used directly,
never added to the terminal state's value). An unfitted model
returns the neutral value 0.5. The result is clamped to
[0, 1]. This is a predicted value, not a verified outcome: it
is a search heuristic, and the plan it points at still needs
the separate verify step plus human approval.
"""
function predict_dynamics_value(model::DynamicsModel,
                                spec::FoodPlanSpec, state::PlanState)
    model.fitted || return 0.5
    step = state[3]
    # Terminal: the value is the delivered share already achieved.
    step >= 2 && return clamp(plan_features(spec, state)[4], 0.0, 1.0)
    game = GI.init(spec, state)
    actions = GI.available_actions(game)
    isempty(actions) && return clamp(plan_features(spec, state)[4], 0.0, 1.0)
    best = 0.0
    for a in actions
        next_feats, reward =
            predict_transition(model, spec, state, a)
        next_state = state_from_features(spec, next_feats)
        # Guard against a predicted successor that does not
        # advance the plan (a model error, not a real
        # transition): value it at the current delivered share.
        if next_state == state
            best = max(best, plan_features(spec, state)[4])
            continue
        end
        # Into a terminal state the predicted reward already IS
        # the final delivered share; otherwise recurse.
        candidate = next_state[3] >= 2 ? reward :
            predict_dynamics_value(model, spec, next_state)
        best = max(best, candidate)
    end
    return clamp(best, 0.0, 1.0)
end

#####
##### MinMaxStats-style value normalisation
#####

"""
    MinMaxStats

Running minimum / maximum statistics over observed values,
in the style of MuZero's MinMaxStats (as in its SelfPlay.jl):
values are normalised into [0, 1] by (v - min) / (max - min).
`count` is the number of finite values observed. A value
stream with no range yet (zero or one distinct values, or no
values at all) normalises to the neutral 0.5 — never NaN, never
a division by zero. Non-finite values are ignored, never
stored. This is an original implementation of the idea, not
copied code.
"""
mutable struct MinMaxStats
    min_value::Float64
    max_value::Float64
    count::Int
    MinMaxStats() = new(Inf, -Inf, 0)
end

"""
    update_minmax!(stats, value)

Record one observed value. Non-finite values are ignored.
Returns the stats.
"""
function update_minmax!(stats::MinMaxStats, value::Float64)
    isfinite(value) || return stats
    stats.min_value = min(stats.min_value, value)
    stats.max_value = max(stats.max_value, value)
    stats.count += 1
    return stats
end

"""
    normalize_value(stats, value) -> Float64

Normalise `value` into [0, 1] using the running statistics:
(v - min) / (max - min), clamped to [0, 1]. With no range yet
(count == 0, or min == max) the result is the neutral 0.5 —
a constant value stream normalises without NaN or division
by zero. A non-finite value normalises to 0.5.
"""
function normalize_value(stats::MinMaxStats, value::Float64)
    (!isfinite(value) || stats.count == 0 ||
     stats.max_value <= stats.min_value) && return 0.5
    return clamp((value - stats.min_value) /
                 (stats.max_value - stats.min_value), 0.0, 1.0)
end

#####
##### The dynamics oracle for MCTS
#####

"""
    DynamicsOracle(model, spec; temperature=0.1)

An oracle the MCTS search can use in place of the rollout
oracle (like LearnedOracle in training_loop.jl, but driven by
the learned dynamics model instead of the linear value model).
Calling it on a state returns (P, V): P scores each available
action by the dynamics-model value of the plan reached by
taking it (softmax over successor values, so actions that
lead to better predicted plans get a higher prior), and V is
the dynamics-model value of the state itself, normalised with
the oracle's MinMaxStats (the stats are updated with the
state's value and every successor value first, so the
normalisation has a range to work with). It is bound to one
spec at a time — the model itself is spec-independent, so a
fresh oracle is built per spec from the same model. A
candidate produced with this oracle is still a candidate
only: it never verifies a plan.
"""
mutable struct DynamicsOracle <: Function
    model::DynamicsModel
    spec::FoodPlanSpec
    temperature::Float64
    stats::MinMaxStats
    DynamicsOracle(model, spec, temperature=0.1) =
        new(model, spec, temperature, MinMaxStats())
end

function (o::DynamicsOracle)(state)
    game = GI.init(o.spec, state)
    actions = GI.available_actions(game)
    if isempty(actions)
        return (Float64[], normalize_value(o.stats, 0.0))
    end
    values = Float64[]
    for a in actions
        next_feats, reward =
            predict_transition(o.model, o.spec, state, a)
        next_state = state_from_features(o.spec, next_feats)
        # Same value semantics as predict_dynamics_value: into
        # a terminal state the predicted reward already IS the
        # final delivered share; otherwise recurse.
        if next_state == state
            push!(values, plan_features(o.spec, state)[4])
        elseif next_state[3] >= 2
            push!(values, reward)
        else
            push!(values,
                  predict_dynamics_value(o.model, o.spec, next_state))
        end
    end
    v_raw = predict_dynamics_value(o.model, o.spec, state)
    for v in values
        update_minmax!(o.stats, v)
    end
    update_minmax!(o.stats, v_raw)
    m = maximum(values)
    exps = exp.((values .- m) ./ o.temperature)
    P = exps ./ sum(exps)
    V = normalize_value(o.stats, v_raw)
    return (P, V)
end

"""
    run_search_with_dynamics(spec, model; nsims, cpuct, seed, selection)

Run MCTS with the dynamics-model oracle over the planning
domain, exactly as run_search_with_oracle does — but the
oracle is built from `model` here. Returns (candidate, trace)
with the candidate a CANDIDATE only (never verified).
Deterministic for a fixed seed.
"""
function run_search_with_dynamics(spec::FoodPlanSpec,
                                  model::DynamicsModel;
                                  nsims::Int=1000,
                                  cpuct::Float64=1.0,
                                  seed::Int=1234,
                                  selection::Symbol=:visits)
    return run_search_with_oracle(
        spec, DynamicsOracle(model, spec);
        nsims=nsims, cpuct=cpuct, seed=seed, selection=selection)
end

#####
##### Reanalyse: refresh search targets, never verified status
#####

"""
    ReanalysedTarget

The refreshed search target for one stored verified sample:
`index` is the sample's position in the memory, `spec_id` and
`state` identify it, `old_outcome` is the outcome recorded
when the sample was stored, `new_target` is the current
dynamics model's (MinMax-normalised) predicted value for the
sample's state, and `verified` is copied unchanged from the
stored sample. Reanalyse updates targets only: it never
recomputes, changes, or invents verified status.
"""
struct ReanalysedTarget
    index::Int
    spec_id::String
    state::PlanState
    old_outcome::Float64
    new_target::Float64
    verified::Bool
end

"""
    reanalyse(memory, model; stats=MinMaxStats())
        -> Vector{ReanalysedTarget}

Revisit every stored verified sample and recompute its search
target with the current dynamics model — the reanalyse step,
as MuZero reanalyses stored games with its current network.
For each sample the new target is the MinMax-normalised
predicted value of the sample's state. The memory itself is
NOT mutated, and the `verified` flag on every target is
copied unchanged from the stored sample: reanalyse refreshes
search targets only and can never turn an unverified sample
verified (or a verified one unverified). A fresh stats object
is used by default, so repeated calls are comparable; pass a
shared stats to accumulate across calls.
"""
function reanalyse(memory::VerifiedMemory, model::DynamicsModel;
                   stats::MinMaxStats=MinMaxStats())
    targets = ReanalysedTarget[]
    for (i, sample) in enumerate(memory_samples(memory))
        raw = predict_dynamics_value(model, sample.spec, sample.state)
        update_minmax!(stats, raw)
        push!(targets, ReanalysedTarget(
            i, sample.spec_id, sample.state, sample.outcome,
            normalize_value(stats, raw), sample.verified))
    end
    return targets
end

#####
##### Held-out evaluation for the dynamics oracle
#####

"""
    evaluate_dynamics_heldout(base_spec, heldout_seeds, model, verify_fn;
                              nsims, cpuct, seed) -> HeldoutResult

Run MCTS on each held-out spec twice — once with the rollout
oracle, once with the dynamics-model oracle built from
`model` — verify each candidate with verify_fn, and return
the HeldoutResult (same type and fields as evaluate_heldout
in training_loop.jl). The existing replacement rule applies
unchanged: the dynamics oracle replaces the current oracle
only if replacement_decision(heldout) is true, i.e. its
held-out verified-PASS rate is at least as high as the
rollout oracle's AND its mean shortage is no worse.
"""
function evaluate_dynamics_heldout(
        base_spec::FoodPlanSpec,
        heldout_seeds::AbstractVector{Int},
        model::DynamicsModel,
        verify_fn;
        nsims::Int=200, cpuct::Float64=1.0, seed::Int=1234)
    rollout_pass = 0
    learned_pass = 0
    rollout_short = 0.0
    learned_short = 0.0
    n = length(heldout_seeds)
    for (i, s) in enumerate(heldout_seeds)
        spec = vary_spec(base_spec, s)
        c_roll = run_search_with_oracle(
            spec, MCTS.RolloutOracle(spec);
            nsims=nsims, cpuct=cpuct, seed=seed + i).candidate
        v_roll = verify_fn(c_roll, spec)
        v_roll.status == "PASS" && (rollout_pass += 1)
        rollout_short += c_roll.shortage
        c_learn = run_search_with_dynamics(
            spec, model; nsims=nsims, cpuct=cpuct,
            seed=seed + i).candidate
        v_learn = verify_fn(c_learn, spec)
        v_learn.status == "PASS" && (learned_pass += 1)
        learned_short += c_learn.shortage
    end
    return HeldoutResult(rollout_pass / n, learned_pass / n,
                         rollout_short / n, learned_short / n, n)
end
